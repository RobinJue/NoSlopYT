import Foundation

/// One downloadable/playable rendition from `streamingData` (`formats` or `adaptiveFormats`).
public struct StreamFormat: Codable, Hashable, Sendable {
    public var itag: Int
    public var url: URL
    public var mimeType: String
    public var bitrate: Int?
    public var width: Int?
    public var height: Int?
    public var fps: Int?
    public var qualityLabel: String?
    public var contentLength: Int64?
    public var approxDurationMs: Int?
    public var audioSampleRate: Int?
    /// Dynamic-range-compressed audio variant (`isDrc`); the plain copy is preferred.
    public var isDRC: Bool
    /// Audio and video in one file (`formats`, as opposed to `adaptiveFormats`).
    public var isProgressive: Bool

    public init(
        itag: Int,
        url: URL,
        mimeType: String,
        bitrate: Int? = nil,
        width: Int? = nil,
        height: Int? = nil,
        fps: Int? = nil,
        qualityLabel: String? = nil,
        contentLength: Int64? = nil,
        approxDurationMs: Int? = nil,
        audioSampleRate: Int? = nil,
        isDRC: Bool = false,
        isProgressive: Bool = false
    ) {
        self.itag = itag
        self.url = url
        self.mimeType = mimeType
        self.bitrate = bitrate
        self.width = width
        self.height = height
        self.fps = fps
        self.qualityLabel = qualityLabel
        self.contentLength = contentLength
        self.approxDurationMs = approxDurationMs
        self.audioSampleRate = audioSampleRate
        self.isDRC = isDRC
        self.isProgressive = isProgressive
    }

    /// `mimeType` starts with "audio/".
    public var isAudioOnly: Bool {
        mimeType.hasPrefix("audio/")
    }

    /// `mimeType` starts with "video/" and the file carries no audio.
    public var isVideoOnly: Bool {
        mimeType.hasPrefix("video/") && !isProgressive
    }

    /// The text inside `codecs="…"` of `mimeType`, or "" when there is none.
    public var codecs: String {
        guard let opening = mimeType.range(of: "codecs=\"") else { return "" }
        let rest = mimeType[opening.upperBound...]
        guard let closing = rest.firstIndex(of: "\"") else { return "" }
        return String(rest[..<closing])
    }

    /// H.264 in MP4 or AAC in MP4: the only combinations AVFoundation can play and mux.
    public var isAVFoundationCompatible: Bool {
        let container = mimeType.split(separator: ";", maxSplits: 1).first
            .map { $0.trimmingCharacters(in: .whitespaces).lowercased() }
        let codecList = self.codecs
        return (container == "video/mp4" && codecList.hasPrefix("avc1"))
            || (container == "audio/mp4" && codecList.hasPrefix("mp4a"))
    }
}

public struct CaptionTrack: Codable, Hashable, Sendable, Identifiable {
    public var languageCode: String
    public var name: String
    public var baseURL: URL
    public var isAutoGenerated: Bool

    public var id: String { "\(languageCode)-\(isAutoGenerated ? "asr" : "std")" }

    public init(languageCode: String, name: String, baseURL: URL, isAutoGenerated: Bool = false) {
        self.languageCode = languageCode
        self.name = name
        self.baseURL = baseURL
        self.isAutoGenerated = isAutoGenerated
    }
}

public struct CaptionCue: Codable, Hashable, Sendable {
    public var start: Double
    public var end: Double
    public var text: String

    public init(start: Double, end: Double, text: String) {
        self.start = start
        self.end = end
        self.text = text
    }
}

/// Playback and download sources for one video, as returned by the `player` endpoint.
public struct StreamInfo: Hashable, Sendable {
    public var videoID: String
    public var title: String
    public var author: String
    public var channelID: String
    public var lengthSeconds: Int
    public var viewCount: Int?
    public var shortDescription: String?
    public var thumbnails: [Thumbnail]
    public var isLive: Bool
    /// HLS master playlist: the playback path. `AVPlayer(url:)` plays it directly.
    public var hlsURL: URL?
    /// Plain-URL formats: the download path.
    public var formats: [StreamFormat]
    public var captions: [CaptionTrack]
    public var expiresAt: Date

    public init(
        videoID: String,
        title: String,
        author: String,
        channelID: String,
        lengthSeconds: Int,
        viewCount: Int? = nil,
        shortDescription: String? = nil,
        thumbnails: [Thumbnail] = [],
        isLive: Bool = false,
        hlsURL: URL? = nil,
        formats: [StreamFormat] = [],
        captions: [CaptionTrack] = [],
        expiresAt: Date
    ) {
        self.videoID = videoID
        self.title = title
        self.author = author
        self.channelID = channelID
        self.lengthSeconds = lengthSeconds
        self.viewCount = viewCount
        self.shortDescription = shortDescription
        self.thumbnails = thumbnails
        self.isLive = isLive
        self.hlsURL = hlsURL
        self.formats = formats
        self.captions = captions
        self.expiresAt = expiresAt
    }

    /// True once `now` is within `margin` seconds of (or past) `expiresAt`.
    public func isExpired(now: Date = Date(), margin: TimeInterval = 120) -> Bool {
        now >= expiresAt.addingTimeInterval(-margin)
    }
}
