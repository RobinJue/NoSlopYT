@Suite struct TimeBoxTests {
    @Test func theValueOfWorkThatFinishesInTime() async {
        let value = await TimeBox.run(.seconds(30)) { 42 }
        #expect(value == 42)
    }

    @Test func workThatThrowsGivesNil() async {
        let value: Int? = await TimeBox.run(.seconds(30)) { throw NoSlopError.network("offline") }
        #expect(value == nil)
    }

    @Test func workThatIsTooSlowIsGivenUpAtTheDeadline() async {
        let clock = ContinuousClock()
        let started = clock.now
        let value: Int? = await TimeBox.run(.milliseconds(100)) {
            try await Task.sleep(for: .seconds(60))
            return 1
        }
        #expect(value == nil)
        #expect(clock.now - started < .seconds(20), "it did not wait for the minute")
    }

    @Test func workThatIgnoresCancellationDoesNotHoldTheCallerUp() async {
        // A call that awaits something that never comes, and does not look at cancellation: a task group would wait for it
        // for ever after `cancelAll()`.
        let gate = DownloadTestGate()
        let clock = ContinuousClock()
        let started = clock.now
        let value: Int? = await TimeBox.run(.milliseconds(100)) {
            await gate.opened()
            return 1
        }
        let waited = clock.now - started
        gate.release()
        #expect(value == nil)
        #expect(waited < .seconds(20), "it came back at the deadline: \(waited)")
    }

    @Test func aCallerThatIsCancelledGetsNilAtOnce() async {
        let clock = ContinuousClock()
        let started = clock.now
        let box = Task { () -> Int? in
            await TimeBox.run(.seconds(60)) {
                try await Task.sleep(for: .seconds(60))
                return 1
            }
        }
        try? await Task.sleep(for: .milliseconds(50))
        box.cancel()
        let value = await box.value
        #expect(value == nil)
        #expect(clock.now - started < .seconds(20))
    }

    @Test func aCallerThatWasCancelledBeforeItStartedGetsNilToo() async {
        let box = Task { () -> Int? in
            while !Task.isCancelled { await Task.yield() }
            return await TimeBox.run(.seconds(60)) {
                try await Task.sleep(for: .seconds(60))
                return 1
            }
        }
        box.cancel()
        #expect(await box.value == nil)
    }
}

// MARK: - The fetcher

/// Lines that closures running anywhere write, read by the test.
private final class CallLog: Sendable {
    private let recorded = Mutex<[String]>([])

    func add(_ line: String) {
        recorded.withLock { $0.append(line) }
    }

    var lines: [String] { recorded.withLock { $0 } }
}

/// Caption text by track id, or an error; counts the requests.
final class ExtrasStubCaptions: CaptionsProviding, Sendable {
    private let state = Mutex(State())

    private struct State {
        var cues: [String: [CaptionCue]] = [:]
        var failing: Set<String> = []
        var hanging: Set<String> = []
        var requested: [String] = []
    }

    let gate = DownloadTestGate()

    func serve(_ track: CaptionTrack, _ cues: [CaptionCue]) {
        state.withLock { $0.cues[track.id] = cues }
    }

    func fail(_ track: CaptionTrack) {
        state.withLock { _ = $0.failing.insert(track.id) }
    }

    func hang(_ track: CaptionTrack) {
        state.withLock { _ = $0.hanging.insert(track.id) }
    }

    var requested: [String] { state.withLock { $0.requested } }

    func cues(for track: CaptionTrack) async throws -> [CaptionCue] {
        let (cues, failing, hanging) = state.withLock { state -> ([CaptionCue]?, Bool, Bool) in
            state.requested.append(track.id)
            return (state.cues[track.id], state.failing.contains(track.id), state.hanging.contains(track.id))
        }
        if hanging { await gate.opened() }
        if failing { throw NoSlopError.network("offline") }
        guard let cues else { throw NoSlopError.http(status: 404) }
        return cues
    }
}

@Suite struct DownloadExtrasFetcherTests {
    private func info(captions: [CaptionTrack] = [ExtrasSample.english]) -> StreamInfo {
        StreamInfo(
            videoID: "jNQXAC9IVRw", title: "Me at the zoo", author: "jawed", channelID: "UC4Q", lengthSeconds: 19,
            captions: captions, expiresAt: .distantFuture
        )
    }

    private func fetcher(
        segments: @escaping DownloadExtrasFetcher.SegmentsSource = { _ in ExtrasSample.segments },
        chapters: @escaping DownloadExtrasFetcher.ChaptersSource = { _ in ExtrasSample.chapters },
        captions: ExtrasStubCaptions,
        language: String? = nil,
        timeout: Duration = .seconds(30),
        maxCaptionTracks: Int = 3
    ) -> DownloadExtrasFetcher {
        DownloadExtrasFetcher(
            segments: segments,
            chapters: chapters,
            captions: captions,
            preferredCaptionLanguage: { language },
            deviceLanguage: "en",
            timeout: timeout,
            maxCaptionTracks: maxCaptionTracks
