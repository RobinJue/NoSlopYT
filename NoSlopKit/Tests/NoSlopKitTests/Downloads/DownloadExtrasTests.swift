@Suite struct DownloadExtrasStoreTests {
    private let root = FileManager.default.temporaryDirectory
        .appendingPathComponent("NoSlopExtrasStoreTests-\(UUID().uuidString)", isDirectory: true)

    private var store: DownloadExtrasStore { DownloadExtrasStore(root: root) }

    private func cleanUp() {
        try? FileManager.default.removeItem(at: root)
    }

    private func listing(_ folder: URL? = nil) -> [String] {
        ((try? FileManager.default.contentsOfDirectory(atPath: (folder ?? store.directory).path)) ?? []).sorted()
    }

    @Test func theFileIsOneJSONPerVideoInAHiddenFolderNextToTheDownloads() {
        defer { cleanUp() }
        #expect(store.merge(ExtrasSample.all, videoID: "jNQXAC9IVRw"))
        #expect(store.directory == root.appendingPathComponent(".extras", isDirectory: true))
        #expect(store.directory.lastPathComponent.hasPrefix("."), "a dot folder, like .work: the Files app does not list it")
        #expect(listing() == ["jNQXAC9IVRw.json"])
        #expect(store.load(videoID: "jNQXAC9IVRw") == ExtrasSample.all)
    }

    @Test func nothingKeptMeansNothingLoaded() {
        defer { cleanUp() }
        #expect(store.load(videoID: "nope") == nil)
        #expect(!FileManager.default.fileExists(atPath: root.path), "reading creates nothing")
    }

    @Test func aMergeKeepsWhatWasThereAndTheVideosAreSeparate() {
        defer { cleanUp() }
        store.merge(DownloadExtras(segments: ExtrasSample.segments), videoID: "a")
        store.merge(DownloadExtras(chapters: ExtrasSample.chapters), videoID: "a")
        store.merge(DownloadExtras(chapters: []), videoID: "b")
        #expect(store.load(videoID: "a") == DownloadExtras(segments: ExtrasSample.segments, chapters: ExtrasSample.chapters))
        #expect(store.load(videoID: "b") == DownloadExtras(chapters: []))
    }

    @Test func aVideoIDCannotLeaveTheFolder() {
        defer { cleanUp() }
        store.merge(DownloadExtras(chapters: []), videoID: "../../Evil/..")
        let written = listing()
        #expect(written.count == 1 && !written[0].contains("/"))
        #expect(store.fileURL(forVideoID: "../../Evil/..").deletingLastPathComponent().standardizedFileURL == store.directory.standardizedFileURL)
        #expect(store.load(videoID: "../../Evil/..") == DownloadExtras(chapters: []))
    }

    @Test func aDamagedFileIsMovedAsideNotDeletedAndCountsAsNotThere() throws {
        defer { cleanUp() }
        store.merge(ExtrasSample.all, videoID: "a")
        let file = store.fileURL(forVideoID: "a")
        try Data("{ this is not json".utf8).write(to: file)

        #expect(store.load(videoID: "a") == nil)
        #expect(listing() == ["a.json.corrupt"], "kept under its new name")
        #expect(try Data(contentsOf: file.appendingPathExtension("corrupt")) == Data("{ this is not json".utf8))

        // The next write starts a clean file; the damaged one stays until a newer damaged one replaces it.
        #expect(store.merge(DownloadExtras(chapters: ExtrasSample.chapters), videoID: "a"))
        #expect(listing() == ["a.json", "a.json.corrupt"])
        #expect(store.load(videoID: "a") == DownloadExtras(chapters: ExtrasSample.chapters))
    }

    @Test func aFileThatCannotBeReadIsLeftAloneAndNothingIsWrittenOverIt() throws {
        defer { cleanUp() }
        // A directory where the file should be: it exists, and the system will not give its content (what data protection
        // before the first unlock looks like from here).
        try FileManager.default.createDirectory(at: store.fileURL(forVideoID: "a"), withIntermediateDirectories: true)
        #expect(store.load(videoID: "a") == nil)
        #expect(!store.merge(ExtrasSample.all, videoID: "a"))
        var isDirectory: ObjCBool = false
        #expect(FileManager.default.fileExists(atPath: store.fileURL(forVideoID: "a").path, isDirectory: &isDirectory) && isDirectory.boolValue)
        #expect(listing() == ["a.json"], "not moved aside either")
    }

    @Test func removeDeletesTheFileAndTheCopyOfADamagedOne() throws {
        defer { cleanUp() }
        store.merge(ExtrasSample.all, videoID: "a")
        store.merge(ExtrasSample.all, videoID: "b")
        try Data("x".utf8).write(to: store.fileURL(forVideoID: "a").appendingPathExtension("corrupt"))
        store.remove(videoID: "a")
        #expect(listing() == ["b.json"])
        store.remove(videoID: "never-there")
        #expect(listing() == ["b.json"])
    }

    @Test func pruneDeletesTheFilesOfVideosThatAreGone() throws {
        defer { cleanUp() }
        for id in ["keep", "gone", "also-gone"] { store.merge(ExtrasSample.all, videoID: id) }
        try Data("x".utf8).write(to: store.fileURL(forVideoID: "gone").appendingPathExtension("corrupt"))
        try Data("not ours".utf8).write(to: store.directory.appendingPathComponent("notes.txt"))

        store.prune(keeping: ["keep", "unrelated"])
        #expect(listing() == ["keep.json", "notes.txt"], "only extras files that belong to nobody go")
        store.prune(keeping: [])
        #expect(listing() == ["notes.txt"])
    }

    @Test func loadOffMainActorGivesTheSameAnswer() async {
        defer { cleanUp() }
        store.merge(ExtrasSample.all, videoID: "a")
        #expect(await store.loadOffMainActor(videoID: "a") == ExtrasSample.all)
        #expect(await store.loadOffMainActor(videoID: "b") == nil)
    }
}

