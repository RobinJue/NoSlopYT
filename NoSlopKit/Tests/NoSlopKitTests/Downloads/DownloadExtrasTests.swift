@Suite struct DownloadExtrasModelTests {
    private func decode(_ json: String) throws -> DownloadExtras {
        try JSONDecoder().decode(DownloadExtras.self, from: Data(json.utf8))
    }

    @Test func roundTripsThroughJSON() throws {
        let data = try JSONEncoder().encode(ExtrasSample.all)
        #expect(try JSONDecoder().decode(DownloadExtras.self, from: data) == ExtrasSample.all)
    }

    @Test func aPartThatIsNotThereIsUnknownNotEmpty() throws {
        #expect(try decode("{}") == DownloadExtras())
        #expect(try decode("{}").isEmpty)
        let onlySegments = try decode(#"{"segments": []}"#)
        #expect(onlySegments.segments == [])
        #expect(onlySegments.chapters == nil && onlySegments.captions == nil)
        #expect(!onlySegments.isEmpty, "an empty list is an answer: SponsorBlock was asked and has nothing")
    }

    @Test func aNilPartIsLeftOutOfTheFile() throws {
        let data = try JSONEncoder().encode(DownloadExtras(chapters: ExtrasSample.chapters))
        let object = try #require(try JSONSerialization.jsonObject(with: data) as? [String: Any])
        #expect(Set(object.keys) == ["chapters"])
    }

    @Test func aDamagedElementCostsOnlyItself() throws {
        let extras = try decode("""
        {
          "segments": [
            {"id": "ok", "category": "sponsor", "actionType": "skip", "start": 1, "end": 2},
            {"id": "future", "category": "a_category_from_the_future", "actionType": "skip", "start": 3, "end": 4},
            {"id": "no-times", "category": "sponsor", "actionType": "skip"}
          ],
          "chapters": [{"title": "Fine", "startSeconds": 5}, {"title": "No start"}, 7],
          "captions": [
            {"track": {"languageCode": "en", "name": "English", "baseURL": "https://example.com/en", "isAutoGenerated": false},
             "cues": [{"start": 0, "end": 1, "text": "kept"}, {"start": "x"}, {"end": 2}]},
            {"track": {"languageCode": "de"}, "cues": []}
          ]
        }
        """)
        #expect(extras.segments?.map(\.id) == ["ok"])
        #expect(extras.chapters?.map(\.title) == ["Fine"])
        #expect(extras.captions?.map(\.track.languageCode) == ["en"])
        #expect(extras.captions?.first?.cues == [CaptionCue(start: 0, end: 1, text: "kept")])
    }

    @Test func aPartOfTheWrongTypeIsUnknownAndTheRestStillReads() throws {
        let extras = try decode(#"{"segments": "none", "chapters": {"a": 1}, "captions": []}"#)
        #expect(extras.segments == nil)
        #expect(extras.chapters == nil)
        #expect(extras.captions == [])
    }

    // MARK: Merging

    @Test func whatTheNewerOneKnowsReplacesAndWhatItDoesNotKnowStays() {
        let older = DownloadExtras(segments: ExtrasSample.segments, chapters: ExtrasSample.chapters)
        let newer = DownloadExtras(segments: [ExtrasSample.segments[1]])
        let merged = older.merging(newer)
        #expect(merged.segments == [ExtrasSample.segments[1]], "what is asked live is right, even when it is shorter")
        #expect(merged.chapters == ExtrasSample.chapters, "a lookup that failed this time costs nothing")
        #expect(merged.captions == nil)
    }

    @Test func anEmptyAnswerReplacesToo() {
        let older = DownloadExtras(segments: ExtrasSample.segments, chapters: ExtrasSample.chapters, captions: ExtrasSample.all.captions)
        let merged = older.merging(DownloadExtras(segments: [], chapters: [], captions: []))
        #expect(merged == DownloadExtras(segments: [], chapters: [], captions: []))
    }

    @Test func captionsAreMergedPerTrack() {
        let older = DownloadExtras(captions: [
            StoredCaptions(track: ExtrasSample.english, cues: [CaptionCue(start: 0, end: 1, text: "old")]),
            StoredCaptions(track: ExtrasSample.german, cues: ExtrasSample.germanCues),
        ])
        let newer = DownloadExtras(captions: [StoredCaptions(track: ExtrasSample.english, cues: ExtrasSample.englishCues)])
        let merged = older.merging(newer)
        #expect(merged.captionTracks.map(\.id) == ["en-std", "de-std"], "the new text of English, the German that was kept")
        #expect(merged.cues(for: ExtrasSample.english) == ExtrasSample.englishCues)
        #expect(merged.cues(for: ExtrasSample.german) == ExtrasSample.germanCues)
    }

    @Test func mergingIntoNothingGivesTheNewerOne() {
        #expect(DownloadExtras().merging(ExtrasSample.all) == ExtrasSample.all)
        #expect(ExtrasSample.all.merging(DownloadExtras()) == ExtrasSample.all)
    }

    // MARK: Captions

    @Test func cuesAreFoundByLanguageAndKindNotByAddress() {
        let extras = ExtrasSample.all
        // The address of a track is signed and changes with every stream info; the track is the same.
        let sameTrackNewAddress = CaptionTrack(
            languageCode: "en", name: "English", baseURL: URL(string: "https://www.youtube.com/api/timedtext?sig=fresh")!
        )
        #expect(extras.cues(for: sameTrackNewAddress) == ExtrasSample.englishCues)
        #expect(extras.cues(for: ExtrasSample.englishAuto) == nil, "the auto-generated track is another track")
        #expect(extras.cues(for: ExtrasSample.french) == nil)
        #expect(DownloadExtras().cues(for: ExtrasSample.english) == nil)
        #expect(extras.captionTracks == [ExtrasSample.english, ExtrasSample.german])
        #expect(DownloadExtras(segments: []).captionTracks.isEmpty)
    }

    // MARK: Which tracks the player offers

    @Test func withoutAnythingKeptTheLiveTracksAreOffered() {
        #expect(DownloadExtras.captionTracks(live: [ExtrasSample.english, ExtrasSample.french], kept: []) == [ExtrasSample.english, ExtrasSample.french])
        #expect(DownloadExtras.captionTracks(live: nil, kept: []).isEmpty, "no stream info yet, and offline there never is")
    }

    @Test func theKeptTracksWorkOfflineSoTheyAreOfferedWithoutTheStreamInfo() {
        let offered = DownloadExtras.captionTracks(live: nil, kept: [ExtrasSample.english, ExtrasSample.german])
        #expect(offered == [ExtrasSample.english, ExtrasSample.german])
    }

    @Test func onceTheLiveTracksArriveTheOnesThatWereNotKeptJoinAndAKeptOneStaysItself() {
        let freshEnglish = CaptionTrack(
            languageCode: "en", name: "English", baseURL: URL(string: "https://www.youtube.com/api/timedtext?sig=fresh")!
        )
        let offered = DownloadExtras.captionTracks(
            live: [freshEnglish, ExtrasSample.french, ExtrasSample.englishAuto],
            kept: [ExtrasSample.english, ExtrasSample.german]
        )
        #expect(offered == [ExtrasSample.english, ExtrasSample.german, ExtrasSample.french, ExtrasSample.englishAuto])
        #expect(offered.first?.baseURL == ExtrasSample.english.baseURL, "the kept English, not the live one: a picker holding it by value keeps it")
    }
}

