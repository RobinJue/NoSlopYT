// What a download keeps next to the video: the model (`DownloadExtras`), its file (`DownloadExtrasStore`), the time box
// and the fetcher that gets it from the services. `DownloadExtrasCaptureTests` drives it through `DownloadManager`.

/// Values the tests share: what a video with two sponsor reads, three chapters and subtitles has.
enum ExtrasSample {
    static let segments = [
        SponsorSegment(id: "seg-intro", category: .intro, start: 0, end: 12.5),
        SponsorSegment(id: "seg-sponsor", category: .sponsor, start: 30, end: 45, videoDuration: 635),
        SponsorSegment(id: "seg-selfpromo", category: .selfpromo, actionType: .skip, start: 120, end: 130),
    ]
    static let chapters = [
        Chapter(title: "Introduction", startSeconds: 0),
        Chapter(title: "The main part", startSeconds: 60, thumbnailURL: URL(string: "https://i.ytimg.com/vi/x/1.jpg")),
        Chapter(title: "Wrap-up", startSeconds: 120),
    ]
    static let english = CaptionTrack(
        languageCode: "en", name: "English", baseURL: URL(string: "https://www.youtube.com/api/timedtext?v=x&lang=en&sig=one")!
    )
    static let german = CaptionTrack(
        languageCode: "de", name: "Deutsch", baseURL: URL(string: "https://www.youtube.com/api/timedtext?v=x&lang=de&sig=two")!
    )
    static let englishAuto = CaptionTrack(
        languageCode: "en", name: "English (auto-generated)",
        baseURL: URL(string: "https://www.youtube.com/api/timedtext?v=x&lang=en&kind=asr&sig=three")!, isAutoGenerated: true
    )
    static let french = CaptionTrack(
        languageCode: "fr", name: "Français", baseURL: URL(string: "https://www.youtube.com/api/timedtext?v=x&lang=fr&sig=four")!
    )
    static let englishCues = [
        CaptionCue(start: 0, end: 2.5, text: "Hello"),
        CaptionCue(start: 2.5, end: 5, text: "and welcome\nto the show"),
    ]
    static let germanCues = [CaptionCue(start: 0, end: 2.5, text: "Hallo")]

    static var all: DownloadExtras {
        DownloadExtras(
            segments: segments,
            chapters: chapters,
            captions: [StoredCaptions(track: english, cues: englishCues), StoredCaptions(track: german, cues: germanCues)]
        )
    }
}

