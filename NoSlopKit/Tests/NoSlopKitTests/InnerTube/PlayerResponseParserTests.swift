    @Test func drcIsDetectedFromTheURLWhenTheFlagIsMissing() throws {
        let json = stream(adaptive: [
            format(140, #"audio/mp4; codecs="mp4a.40.2""#, url: "https://rr1.googlevideo.com/videoplayback?itag=140&xtags=drc%3D1&mime=audio"),
            format(140, #"audio/mp4; codecs="mp4a.40.2""#, url: "https://rr1.googlevideo.com/videoplayback?itag=140&mime=audio"),
            format(139, #"audio/mp4; codecs="mp4a.40.5""#, ["isDrc": true]),
