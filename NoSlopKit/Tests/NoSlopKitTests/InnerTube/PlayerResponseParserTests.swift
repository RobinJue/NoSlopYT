    // MARK: Stream info

    @Test func expiryDefaultsToSixHoursAndComesFromTheResponseWhenPresent() throws {
        let missing = try PlayerResponseParser.parse(stream(), now: t0)
        #expect(missing.expiresAt == t0.addingTimeInterval(21_540))
        let asString = try PlayerResponseParser.parse(stream(expiresInSeconds: "3600"), now: t0)
        #expect(asString.expiresAt == t0.addingTimeInterval(3_600))
        let asNumber = try PlayerResponseParser.parse(stream(expiresInSeconds: 1800), now: t0)
        #expect(asNumber.expiresAt == t0.addingTimeInterval(1_800))
        for unusable: JSON in ["soon", "inf", "nan", "0", "-5", 0] {
            let info = try PlayerResponseParser.parse(stream(expiresInSeconds: unusable), now: t0)
            #expect(info.expiresAt == t0.addingTimeInterval(21_540), "expiresInSeconds: \(unusable)")
        }
    }

