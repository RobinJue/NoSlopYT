private let t0 = Date(timeIntervalSince1970: 1_800_000_000)

/// A `player` response with the given `playabilityStatus`.
private func playability(_ status: String, reason: String? = nil, extra: [String: JSON] = [:]) -> JSON {
    var object: [String: JSON] = ["status": .string(status)]
    if let reason { object["reason"] = .string(reason) }
    for (key, value) in extra { object[key] = value }
    return ["playabilityStatus": .object(object)]
}

private func stream(
    id: String = "abc12345678",
    hls: String? = "https://manifest.googlevideo.com/api/manifest/hls_variant/x",
    formats: [JSON]? = nil,
    adaptive: [JSON]? = nil,
    expiresInSeconds: JSON? = nil,
    details: [String: JSON] = [:],
    captions: [JSON]? = nil
) -> JSON {
    var streaming: [String: JSON] = [:]
    if let hls { streaming["hlsManifestUrl"] = .string(hls) }
    if let formats { streaming["formats"] = .array(formats) }
    if let adaptive { streaming["adaptiveFormats"] = .array(adaptive) }
    if let expiresInSeconds { streaming["expiresInSeconds"] = expiresInSeconds }

    var videoDetails: [String: JSON] = [
        "videoId": .string(id), "title": "Title", "lengthSeconds": "61", "channelId": "UCchannel", "author": "Author",
    ]
    for (key, value) in details { videoDetails[key] = value }

    var root: [String: JSON] = [
        "playabilityStatus": ["status": "OK"],
        "streamingData": .object(streaming),
        "videoDetails": .object(videoDetails),
    ]
    if let captions {
        root["captions"] = ["playerCaptionsTracklistRenderer": ["captionTracks": .array(captions)]]
    }
    return .object(root)
}

private func format(_ itag: Int, _ mime: String, url: String? = "https://rr1.googlevideo.com/videoplayback?itag=1", _ extra: [String: JSON] = [:]) -> JSON {
    var object: [String: JSON] = ["itag": .number(Double(itag)), "mimeType": .string(mime)]
    if let url { object["url"] = .string(url) }
    for (key, value) in extra { object[key] = value }
    return .object(object)
}

private func track(_ language: String, _ name: String, kind: String? = nil, url: String? = "https://www.youtube.com/api/timedtext?v=x") -> JSON {
    var object: [String: JSON] = ["languageCode": .string(language), "name": ["runs": [["text": .string(name)]]]]
    if let url { object["baseUrl"] = .string(url) }
    if let kind { object["kind"] = .string(kind) }
    return .object(object)
}

@Suite struct PlayerResponseParserTests {
    // MARK: From the plan

    @Test func bigBuckBunny() throws {
        let info = try PlayerResponseParser.parse(try Fixture.json("player_visionos_bigbuckbunny.json"), now: t0)
        #expect(info.videoID == "aqz-KE-bpKQ")
        #expect(info.title == "Big Buck Bunny 60fps 4K - Official Blender Foundation Short Film")
        #expect(info.lengthSeconds == 635)
        #expect(info.hlsURL?.host == "manifest.googlevideo.com")
        #expect(Set(info.formats.filter { $0.mimeType.contains("avc1") }.map(\.itag)) == [299, 298, 135, 134, 133, 160])
        #expect(Set(info.formats.filter { $0.itag == 140 }.map(\.isDRC)) == [false, true])
        #expect(info.formats.first { $0.itag == 140 && !$0.isDRC }?.approxDurationMs == 634_624)
        #expect(info.formats.first { $0.itag == 140 && !$0.isDRC }?.contentLength == 10_271_496)
        #expect(info.expiresAt == t0.addingTimeInterval(21540))
        #expect(!info.isLive)
    }

