    @Test func entriesWithoutAPlainURLAreSkipped() throws {
        let cipher = format(18, #"video/mp4; codecs="avc1.42001E, mp4a.40.2""#, url: nil, ["signatureCipher": "s=abc&sp=sig&url=https%3A%2F%2Fexample.com"])
        let blank = format(19, "video/mp4", url: "")
        let json = stream(hls: nil, adaptive: [cipher, blank, format(22, #"video/mp4; codecs="avc1.64001F""#)])
        let info = try PlayerResponseParser.parse(json, now: t0)
        #expect(info.formats.map(\.itag) == [22])
    }

    @Test func progressiveFormatsAreFlaggedAndComeFirst() throws {
        let json = stream(
            formats: [format(18, #"video/mp4; codecs="avc1.42001E, mp4a.40.2""#, ["width": 640, "height": 360])],
            adaptive: [format(137, #"video/mp4; codecs="avc1.640028""#)]
        )
        let info = try PlayerResponseParser.parse(json, now: t0)
        #expect(info.formats.map(\.itag) == [18, 137])
        #expect(info.formats.map(\.isProgressive) == [true, false])
        #expect(info.formats.first?.isVideoOnly == false)
    }

    @Test func numbersMayArriveAsStringsOrNumbers() throws {
        let json = stream(adaptive: [format(140, #"audio/mp4; codecs="mp4a.40.2""#, [
            "contentLength": "5000000000",       // beyond Int32
            "approxDurationMs": 1234,
            "bitrate": "130992",
            "audioSampleRate": 48000,
        ])])
        let audio = try #require(PlayerResponseParser.parse(json, now: t0).formats.first)
        #expect(audio.contentLength == 5_000_000_000)
        #expect(audio.approxDurationMs == 1_234)
        #expect(audio.bitrate == 130_992)
        #expect(audio.audioSampleRate == 48_000)
    }

    @Test func optionalFormatFieldsMayBeMissing() throws {
