    @Test func noStreamsAtAllIsNotPlayableYet() {
        let expected = NoSlopError.notPlayableYet(reason: "No playable streams were returned for this video.")
        #expect(throws: expected) { try PlayerResponseParser.parse(stream(hls: nil), now: t0) }
        #expect(throws: expected) { try PlayerResponseParser.parse(stream(hls: nil, formats: [], adaptive: []), now: t0) }
        #expect(throws: expected) { try PlayerResponseParser.parse(stream(hls: ""), now: t0) }
        var withoutStreamingData = stream()
        if case .object(var object) = withoutStreamingData {
            object["streamingData"] = nil
            withoutStreamingData = .object(object)
        }
        #expect(throws: expected) { try PlayerResponseParser.parse(withoutStreamingData, now: t0) }
    }

    @Test func missingVideoDetailsIsADecodingError() {
        let json: JSON = ["playabilityStatus": ["status": "OK"], "streamingData": ["hlsManifestUrl": "https://manifest.googlevideo.com/x"]]
        do {
            _ = try PlayerResponseParser.parse(json, now: t0)
            Issue.record("expected a decoding error")
        } catch let error as NoSlopError {
            guard case .decoding = error else {
                Issue.record("expected .decoding, got \(error)")
                return
            }
        } catch {
            Issue.record("unexpected error \(error)")
        }
    }

