    @Test func captionTracksFollowTheResponseOrder() throws {
        let json = stream(captions: [
            track("en", "English"),
            track("en", "English (auto-generated)", kind: "asr"),
            track("de-DE", "German (Germany)"),
        ])
        let info = try PlayerResponseParser.parse(json, now: t0)
        #expect(info.captions.map(\.languageCode) == ["en", "en", "de-DE"])
        #expect(info.captions.map(\.isAutoGenerated) == [false, true, false])
        #expect(info.captions.map(\.id) == ["en-std", "en-asr", "de-DE-std"])
        #expect(info.captions.first?.baseURL.absoluteString == "https://www.youtube.com/api/timedtext?v=x")
    }

