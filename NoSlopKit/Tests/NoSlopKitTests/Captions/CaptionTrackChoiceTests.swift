import Foundation
import Testing
@testable import NoSlopKit

@Suite struct CaptionTrackChoiceTests {
    private func track(_ language: String, auto: Bool = false) -> CaptionTrack {
        CaptionTrack(
            languageCode: language,
            name: auto ? "\(language) (auto-generated)" : language,
            baseURL: URL(string: "https://www.youtube.com/api/timedtext?lang=\(language)\(auto ? "&kind=asr" : "")")!,
            isAutoGenerated: auto
        )
    }

    private func ids(_ tracks: [CaptionTrack]) -> [String] {
        tracks.map(\.id)
    }

    // MARK: matching

    @Test func aLanguageMatchesItsRegionalVariants() {
        let tracks = [track("de"), track("en-US"), track("pt-BR")]
        #expect(CaptionTrackChoice.matching(in: tracks, language: "en")?.languageCode == "en-US")
        #expect(CaptionTrackChoice.matching(in: tracks, language: "EN_gb")?.languageCode == "en-US")
        #expect(CaptionTrackChoice.matching(in: tracks, language: "pt")?.languageCode == "pt-BR")
        #expect(CaptionTrackChoice.matching(in: tracks, language: "fr") == nil)
    }

    @Test func aWrittenTrackBeatsAnAutoGeneratedOneOfTheSameLanguage() {
        let tracks = [track("en", auto: true), track("en")]
        #expect(CaptionTrackChoice.matching(in: tracks, language: "en")?.isAutoGenerated == false)
        #expect(CaptionTrackChoice.matching(in: [track("en", auto: true)], language: "en")?.isAutoGenerated == true)
    }

    // MARK: preferred

    @Test func theViewersLanguageComesBeforeTheDevicesAndBeforeEnglish() {
        let tracks = [track("en"), track("de"), track("fr")]
        #expect(CaptionTrackChoice.preferred(in: tracks, language: "fr", deviceLanguage: "de")?.languageCode == "fr")
        #expect(CaptionTrackChoice.preferred(in: tracks, language: nil, deviceLanguage: "de")?.languageCode == "de")
        #expect(CaptionTrackChoice.preferred(in: tracks, language: "", deviceLanguage: "es")?.languageCode == "en")
    }

    @Test func withNoneOfThoseTheFirstWrittenTrackWins() {
        let tracks = [track("ja", auto: true), track("ko"), track("zh")]
        #expect(CaptionTrackChoice.preferred(in: tracks, language: "fr", deviceLanguage: "de")?.languageCode == "ko")
        #expect(CaptionTrackChoice.preferred(in: [track("ja", auto: true)], language: nil, deviceLanguage: nil)?.languageCode == "ja")
        #expect(CaptionTrackChoice.preferred(in: [], language: "en", deviceLanguage: "en") == nil)
    }

    // MARK: tracksToKeep

    @Test func theDefaultComesFirstThenTheOtherPreferredLanguagesThenTheRest() {
        let tracks = [track("es"), track("fr", auto: true), track("en"), track("de"), track("ja"), track("en", auto: true)]
        // Viewer: German. Device: Spanish. Then English.
        let kept = CaptionTrackChoice.tracksToKeep(in: tracks, language: "de", deviceLanguage: "es", limit: 10)
        #expect(ids(kept) == ["de-std", "es-std", "en-std", "ja-std", "fr-asr", "en-asr"])
        #expect(kept.first == CaptionTrackChoice.preferred(in: tracks, language: "de", deviceLanguage: "es"))
    }

    @Test func theLimitCutsTheListAfterTheBestOnes() {
        let tracks = [track("es"), track("fr"), track("en"), track("de")]
        #expect(ids(CaptionTrackChoice.tracksToKeep(in: tracks, language: nil, deviceLanguage: "de", limit: 3)) == ["de-std", "en-std", "es-std"])
        #expect(ids(CaptionTrackChoice.tracksToKeep(in: tracks, language: nil, deviceLanguage: "de", limit: 1)) == ["de-std"])
        #expect(CaptionTrackChoice.tracksToKeep(in: tracks, language: nil, deviceLanguage: "de", limit: 0).isEmpty)
    }

    @Test func aTrackIsNeverKeptTwiceAndAVideoWithoutCaptionsKeepsNone() {
        let tracks = [track("en"), track("en", auto: true)]
        let kept = CaptionTrackChoice.tracksToKeep(in: tracks, language: "en", deviceLanguage: "en", limit: 5)
        #expect(ids(kept) == ["en-std", "en-asr"])
        #expect(CaptionTrackChoice.tracksToKeep(in: [], language: "en", deviceLanguage: "en", limit: 3).isEmpty)
    }
}
