import Foundation
import Testing
@testable import NoSlopKit

// Opt-in tests against the real YouTube: `NOSLOP_LIVE=1 swift test --package-path NoSlopKit --filter Live`.
// Without the variable the whole suite is skipped, so the normal test run never touches the network.
// YouTube rate-limits, so each test makes only a handful of requests and the suite runs one test at a time.

private let liveEnabled = ProcessInfo.processInfo.environment["NOSLOP_LIVE"] == "1"

/// "Me at the zoo": the oldest video on YouTube, 19 seconds, with captions, always available.
private let zooID = "jNQXAC9IVRw"
private let rickrollID = "dQw4w9WgXcQ"
private let blenderChannelID = "UCSMOQeBJ2RAnuFungnQOxLg"

private func makeLiveClient(_ http: any HTTPClient = URLSessionHTTPClient()) -> InnerTubeClient {
    InnerTubeClient(http: http, config: InnerTubeConfig(hl: "en", gl: "US"), visitorStore: InMemoryVisitorDataStore())
}

private func get(_ http: any HTTPClient, _ url: URL, range: String? = nil) async throws -> (Data, HTTPURLResponse) {
    var request = URLRequest(url: url)
    request.timeoutInterval = 30
    if let range { request.setValue(range, forHTTPHeaderField: "Range") }
    return try await http.send(request)
}

@Suite(.serialized, .enabled(if: liveEnabled, "Set NOSLOP_LIVE=1 to run the live YouTube tests."))
struct LiveSmokeTests {
    @Test func streamsPlayAndRangeRequestsWork() async throws {
        let http = URLSessionHTTPClient()
        let resolver = InnerTubeStreamResolver(client: makeLiveClient(http))
        let info = try await resolver.streamInfo(videoID: zooID)

        #expect(info.videoID == zooID)
        #expect(info.lengthSeconds > 0)
        #expect(!info.isLive)
        #expect(info.expiresAt > Date())

        // The playback path: an HLS master playlist that AVPlayer can open directly.
        let hlsURL = try #require(info.hlsURL)
        let (playlist, playlistResponse) = try await get(http, hlsURL)
        #expect(playlistResponse.statusCode == 200)
        #expect(String(decoding: playlist.prefix(7), as: UTF8.self) == "#EXTM3U")

        // The download path: plain H.264 URLs answer Range requests.
        let avc1 = try #require(info.formats.first { $0.mimeType.contains("avc1") })
        let (chunk, chunkResponse) = try await get(http, avc1.url, range: "bytes=0-1023")
        #expect(chunkResponse.statusCode == 206)
        #expect(chunk.count == 1024)
        #expect(info.formats.contains { $0.isAudioOnly && $0.isAVFoundationCompatible && !$0.isDRC })
    }

    @Test func captionsDownloadAsWebVTT() async throws {
        let http = URLSessionHTTPClient()
        let info = try await InnerTubeStreamResolver(client: makeLiveClient(http)).streamInfo(videoID: rickrollID)
        let track = try #require(info.captions.first { !$0.isAutoGenerated })
        let cues = try await CaptionsService(http: http).cues(for: track)
        #expect(cues.count > 10)
        #expect(cues.allSatisfy { $0.end > $0.start && !$0.text.isEmpty })
        #expect(cues.map(\.start) == cues.map(\.start).sorted())
    }

    @Test func channelRSSHasRecentUploads() async throws {
        let videos = try await RSSFeedFetcher(http: URLSessionHTTPClient()).latestVideos(channelID: blenderChannelID)
        #expect(videos.count >= 5)
        #expect(videos.allSatisfy { $0.channel?.id == blenderChannelID && $0.publishedAt != nil && !$0.title.isEmpty })
        let newest = try #require(videos.first?.publishedAt)
        #expect(newest > Date().addingTimeInterval(-365 * 86_400))
    }

    @Test func suggestionsComeBack() async throws {
        let http = URLSessionHTTPClient()
        let service = InnerTubeYouTubeService(client: makeLiveClient(http), http: http)
        let suggestions = try await service.suggestions(for: "blender tut")
        #expect(suggestions.count >= 3)
        #expect(suggestions.contains { $0.hasPrefix("blender tut") })
    }

    @Test func aHandleResolvesToItsChannel() async throws {
        let http = URLSessionHTTPClient()
        let service = InnerTubeYouTubeService(client: makeLiveClient(http), http: http)
        let resolved = try await service.resolve(url: try #require(URL(string: "https://www.youtube.com/@BlenderOfficial")))
        #expect(resolved == .channel(id: blenderChannelID))
        // …and a handle that does not exist is "no result", not an error.
        let missing = try await service.resolve(url: try #require(URL(string: "https://www.youtube.com/@zz-noslop-no-such-handle-91827")))
        #expect(missing == nil)
    }

    @Test func webEndpointsAnswerWithTheTransportAlone() async throws {
        // The Task 3/4 parsers decide what the answers mean; this proves the transport (headers, context,
        // visitorData) is accepted by the real endpoints.
        let client = makeLiveClient()
        let search = try await client.post(endpoint: "search", profile: .web, body: ["query": "blender donut tutorial"])
        #expect(!search.findAll("videoRenderer").isEmpty)

        let next = try await client.post(endpoint: "next", profile: .web, body: ["videoId": .string(zooID)])
        #expect(next.first("videoPrimaryInfoRenderer") != nil || next.first("videoMetadataRenderer") != nil || next.first("title") != nil)

        let browse = try await client.post(endpoint: "browse", profile: .web, body: ["browseId": .string(blenderChannelID), "params": .string(ChannelParser.tabParams[.videos] ?? "")])
        #expect(browse.first("header") != nil || browse.first("pageHeaderRenderer") != nil || browse.first("c4TabbedHeaderRenderer") != nil)
    }

    @Test func visitorDataIsIssued() async throws {
        let value = try await makeLiveClient().visitorData()
        #expect(value.hasPrefix("Cg"))
        #expect(value.count > 20)
    }
}
